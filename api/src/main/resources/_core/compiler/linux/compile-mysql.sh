# Security validation functions
validate_database_name() {
    local db_name="$1"
    # Allow only alphanumeric, underscore, and dash characters
    if [[ ! "$db_name" =~ ^[a-zA-Z0-9_-]+$ ]]; then
        echo "Error: Invalid database name: $db_name" >&2
        echo "Database names must contain only alphanumeric characters, underscores, and dashes" >&2
        exit 1
    fi
    if [[ ${#db_name} -gt 64 ]]; then
        echo "Error: Database name too long: $db_name (max 64 characters)" >&2
        exit 1
    fi
}

validate_path() {
    local path="$1"
    local base_dir="$2"
    
    # Resolve to absolute path
    local resolved_path
    resolved_path=$(realpath -m "$path" 2>/dev/null) || {
        echo "Error: Invalid path: $path" >&2
        exit 1
    }
    
    # Check if path is within allowed base directory
    if [[ -n "$base_dir" ]]; then
        local resolved_base
        resolved_base=$(realpath -m "$base_dir" 2>/dev/null) || {
            echo "Error: Invalid base directory: $base_dir" >&2
            exit 1
        }
        if [[ "$resolved_path" != "$resolved_base"* ]]; then
            echo "Error: Path traversal attempt detected: $path" >&2
            echo "Path must be within: $base_dir" >&2
            exit 1
        }
    fi
    
    echo "$resolved_path"
}

# Validate schema name to prevent SQL injection
validate_schema_name() {
    local schema="$1"
    # Allow only alphanumeric, underscore characters
    if [[ ! "$schema" =~ ^[a-zA-Z0-9_]+$ ]]; then
        echo "Error: Invalid schema name: $schema" >&2
        echo "Schema names must contain only alphanumeric characters and underscores" >&2
        exit 1
    fi
    if [[ ${#schema} -gt 64 ]]; then
        echo "Error: Schema name too long: $schema (max 64 characters)" >&2
        exit 1
    fi
}

# Validate integer parameters
validate_integer() {
    local value="$1"
    local param_name="$2"
    local min="${3:-0}"
    local max="${4:-2147483647}"
    
    if [[ ! "$value" =~ ^[0-9]+$ ]]; then
        echo "Error: Invalid ${param_name}: must be an integer, got: ${value}" >&2
        exit 1
    fi
    
    if [[ $value -lt $min || $value -gt $max ]]; then
        echo "Error: ${param_name} out of range: ${value} (must be between ${min} and ${max})" >&2
        exit 1
    fi
}

