# Common function to read JSON configurations from config directory
# Parameters:
#   $1 - exclude_file: File to exclude (e.g., "reports.json")
# Returns:
#   JSON string with combined configurations
read_json_configurations() {
    local exclude_file="${1:-}"
    local json_contents="{\"flat_report_metadata\":["
    local first_file=true
    
    for filename in "${config_dir}"/*.json; do
        # Skip if file doesn't exist (no .json files)
        [[ ! -f "${filename}" ]] && continue
        
        # Skip excluded file
        if [[ -n "${exclude_file}" && "${filename}" = "${config_dir}/${exclude_file}" ]]; then
            continue
        fi
        
        # Add comma separator after first file
        if [[ "${first_file}" = false ]]; then
            json_contents="${json_contents},"
        fi
        
        json_contents="${json_contents}$(cat "${filename}")"
        first_file=false
    done
    
    json_contents="${json_contents}]}"
    
    # Validate JSON structure
    if ! echo "${json_contents}" | jq . > /dev/null 2>&1; then
        echo "Error: Invalid JSON structure in configuration files" >&2
        exit 1
    fi
    
    echo "${json_contents}"
}

# Common function to escape JSON for SQL
escape_json_for_sql() {
    local json="$1"
    # Escape single quotes for SQL safety
    echo "${json}" | sed "s/'/\\\\\\\\'\\\\\\\\'/g"
}

